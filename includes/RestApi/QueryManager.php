<?php
/**
 * Query Manager for GSlider Blocks.
 *
 * Extends the WordPress REST API query parameters for post collections,
 * allowing blocks in the Gutenberg editor to filter by custom metadata,
 * advanced order parameters, and other fields.
 *
 * @package GSlider\RestApi
 * @since   1.2.0
 */

namespace GSlider\RestApi;

use GSlider\Traits\SingletonTrait;

if ( ! defined( 'ABSPATH' ) ) {
    exit;
}

if ( ! class_exists( 'QueryManager' ) ) {

    /**
     * Handles extension of REST API endpoints for advanced query support.
     *
     * @since 1.2.0
     */
    class QueryManager {
        use SingletonTrait;

        /**
         * Registers filters for REST API queries.
         *
         * @since 1.2.0
         *
         * @return void
         */
        public function register() {
            add_action( 'init', [ $this, 'register_filters' ], 20 );
        }

        /**
         * Hooks into REST API collection parameters and query arguments for all public post types.
         *
         * @since 1.2.0
         *
         * @return void
         */
        public function register_filters() {
            $post_types = get_post_types( [ 'show_in_rest' => true ], 'names' );
            foreach ( $post_types as $post_type ) {
                add_filter( "rest_{$post_type}_collection_params", [ $this, 'add_custom_query_params' ] );
                add_filter( "rest_{$post_type}_query", [ $this, 'apply_custom_query_params' ], 10, 2 );
            }
        }

        /**
         * Registers additional query parameters for the REST API post type collections.
         *
         * @since 1.2.0
         *
         * @param array $query_params The original query parameters.
         * @return array Modified query parameters.
         */
        public function add_custom_query_params( $query_params ) {
            // Extend orderby values
            if ( isset( $query_params['orderby']['enum'] ) ) {
                $query_params['orderby']['enum'][] = 'rand';
                $query_params['orderby']['enum'][] = 'comment_count';
                $query_params['orderby']['enum'][] = 'meta_value';
                $query_params['orderby']['enum'][] = 'meta_value_num';
                $query_params['orderby']['enum'][] = 'menu_order';
            }

            // Register custom meta-query parameters
            $query_params['meta_key'] = [
                'description'       => __( 'Meta key to filter by.', 'gslider-blocks' ),
                'type'              => 'string',
                'sanitize_callback' => 'sanitize_text_field',
            ];
            $query_params['meta_value'] = [
                'description'       => __( 'Meta value to filter by.', 'gslider-blocks' ),
                'type'              => 'string',
                'sanitize_callback' => 'sanitize_text_field',
            ];
            $query_params['meta_compare'] = [
                'description'       => __( 'Comparison operator for meta query.', 'gslider-blocks' ),
                'type'              => 'string',
                'enum'              => [ '=', '!=', '>', '>=', '<', '<=', 'LIKE', 'NOT LIKE', 'EXISTS', 'NOT EXISTS' ],
                'sanitize_callback' => 'sanitize_text_field',
            ];

            return $query_params;
        }

        /**
         * Applies the custom query arguments to the WP_Query args generated by the REST controller.
         *
         * @since 1.2.0
         *
         * @param array           $args    The WP_Query arguments.
         * @param \WP_REST_Request $request The REST request object.
         * @return array Modified WP_Query arguments.
         */
        public function apply_custom_query_params( $args, $request ) {
            // Apply custom orderby parameters
            $orderby = $request->get_param( 'orderby' );
            if ( in_array( $orderby, [ 'rand', 'comment_count', 'meta_value', 'meta_value_num', 'menu_order' ], true ) ) {
                $args['orderby'] = $orderby;
            }

            // Apply custom meta query parameters
            $meta_key     = $request->get_param( 'meta_key' );
            $meta_value   = $request->get_param( 'meta_value' );
            $meta_compare = $request->get_param( 'meta_compare' );

            if ( ! empty( $meta_key ) ) {
                $meta_query = [
                    'key'     => sanitize_text_field( $meta_key ),
                    'compare' => ! empty( $meta_compare ) ? sanitize_text_field( $meta_compare ) : '=',
                ];

                if ( isset( $meta_value ) && ! in_array( $meta_compare, [ 'EXISTS', 'NOT EXISTS' ], true ) ) {
                    $meta_query['value'] = sanitize_text_field( $meta_value );
                }

                $args['meta_query'] = [ $meta_query ];
            }

            return $args;
        }
    }
}

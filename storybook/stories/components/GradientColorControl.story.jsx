import { useState } from 'react';
import GradientColorControl from '@Components/gradient-color-control';

export default {
	title: 'Components/Color/GradientColorControl',
	component: GradientColorControl,
	tags: [ 'autodocs' ],
	parameters: {
		docs: {
			description: {
				component:
					'GradientColorControl provides an advanced gradient management interface combining WordPress core GradientPicker (supporting linear and radial gradients, angle rotation, and color stops) with an extensible custom CSS gradient textarea mode.',
			},
		},
	},
	argTypes: {
		label: {
			control: 'text',
			description: 'Label displayed in the base control wrapper',
		},
		globalCustomGradientSwitcher: {
			control: 'boolean',
			description:
				'Whether the custom gradient mode is active (toggles between GradientPicker and custom TextareaControl)',
		},
		globalCustomGradientInputValue: {
			control: 'text',
			description:
				'Custom CSS gradient string entered directly in textarea mode',
		},
		globalGradientColor: {
			control: 'text',
			description:
				'Current gradient string generated by the preset GradientPicker',
		},
		setGlobalCustomGradientSwitcher: {
			action: 'customGradientSwitcherChanged',
			description: 'Callback fired when custom gradient toggle switches',
		},
		setGlobalCustomGradientInputValue: {
			action: 'customGradientInputChanged',
			description:
				'Callback fired when custom gradient textarea value updates',
		},
		setGlobalGradientColor: {
			action: 'gradientColorChanged',
			description:
				'Callback fired when gradient value updates from the picker',
		},
	},
};

export const Default = {
	render: ( args ) => {
		const [ isCustom, setIsCustom ] = useState(
			args.globalCustomGradientSwitcher || false
		);
		const [ customValue, setCustomValue ] = useState(
			args.globalCustomGradientInputValue ||
				'linear-gradient(135deg, #12c2e9 0%, #c471ed 50%, #f64f59 100%)'
		);
		const [ presetValue, setPresetValue ] = useState(
			args.globalGradientColor ||
				'linear-gradient(135deg, rgba(6,147,227,1) 0%, rgb(155,81,224) 100%)'
		);

		const activeGradient = isCustom ? customValue : presetValue;

		return (
			<div>
				<GradientColorControl
					label={ args.label || 'Background Gradient' }
					globalCustomGradientSwitcher={ isCustom }
					setGlobalCustomGradientSwitcher={ ( val ) => {
						setIsCustom( val );
						args.setGlobalCustomGradientSwitcher?.( val );
					} }
					globalCustomGradientInputValue={ customValue }
					setGlobalCustomGradientInputValue={ ( val ) => {
						setCustomValue( val );
						args.setGlobalCustomGradientInputValue?.( val );
					} }
					globalGradientColor={ presetValue }
					setGlobalGradientColor={ ( val ) => {
						setPresetValue( val );
						args.setGlobalGradientColor?.( val );
					} }
				/>

				<div
					style={ {
						marginTop: '20px',
						padding: '16px',
						borderRadius: '6px',
						background: '#f8fafc',
						border: '1px solid #e2e8f0',
					} }
				>
					<div
						style={ {
							fontSize: '11px',
							fontWeight: 600,
							textTransform: 'uppercase',
							letterSpacing: '0.05em',
							color: '#64748b',
							marginBottom: '10px',
						} }
					>
						Live Gradient Preview
					</div>
					<div
						style={ {
							height: '90px',
							borderRadius: '6px',
							background: activeGradient || 'transparent',
							display: 'flex',
							alignItems: 'center',
							justifyContent: 'center',
							boxShadow: '0 4px 12px rgba(0,0,0,0.1)',
							transition: 'background 0.3s ease',
						} }
					>
						<span
							style={ {
								padding: '4px 10px',
								borderRadius: '4px',
								background: 'rgba(255, 255, 255, 0.95)',
								color: '#0f172a',
								fontSize: '11px',
								fontFamily: 'monospace',
								fontWeight: 600,
								maxWidth: '90%',
								overflow: 'hidden',
								textOverflow: 'ellipsis',
								whiteSpace: 'nowrap',
								boxShadow: '0 1px 3px rgba(0,0,0,0.15)',
							} }
						>
							{ activeGradient || 'No Gradient Selected' }
						</span>
					</div>
				</div>
			</div>
		);
	},
	args: {
		label: 'Slide Background Gradient',
		globalCustomGradientSwitcher: false,
		globalGradientColor:
			'linear-gradient(135deg, rgba(6,147,227,1) 0%, rgb(155,81,224) 100%)',
		globalCustomGradientInputValue:
			'linear-gradient(135deg, #12c2e9 0%, #c471ed 50%, #f64f59 100%)',
	},
};

